/**
 * 按等级取一张表里的基础伤害
 *
 * 查不到返回 0 而非 undefined（`undefined` 参与运算传成 `NaN`、模板显示为空白），等级超范围说明版本对不上、调用方据此可判。
 * @param table 数值表
 * @param level 等级
 * @returns 基础伤害；查不到时 0
 */
export function baseDmgAt(table: Readonly<Record<string, number>>, level: number): number {
  return table[String(level)] ?? 0
}
