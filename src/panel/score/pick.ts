/**
 * 模块职责：评分骨架里「按权重挑最优的几条」那一步 —— 三个游戏共用同一副次序
 * 依赖方向：无依赖，纯函数
 * 生命周期：无状态
 * 注意事项：这一层只管次序、不管筛选（两侧筛选口径不同，收进来不划算），只收唯一不能出错的事：并列时谁在前。
 *          **并列时取候选列表里靠后的那个**（做法：稳定升序再整体反转）：改成直接降序会让芭芭拉一类 `hp`/`heal` 同权角色挑中 `hp` 而非 `heal`，
 *          主词条挑中谁决定副词条禁用谁、整套评分随之偏移。绝区零那路**向原神星铁靠**。
 */

/**
 * 按权重降序排一列候选，并列时取靠后的那个
 *
 * 稳定升序再整体反转，理由见文件头。**不筛不截**：交回的是整列排好的，筛选与取前几条由调用方做。
 * @param list 候选，次序有承载作用（并列时按它的逆序）
 * @param weightOf 取一项的权重
 * @returns 同一批候选，按权重降序；并列者按入参的逆序
 */
export function byWeightDesc<T>(list: readonly T[], weightOf: (one: T) => number): T[] {
  const out = [...list]
  // 稳定升序 + 整体反转：并列时取候选列表里靠后的那个，见文件头
  out.sort((a, b) => weightOf(a) - weightOf(b))
  out.reverse()
  return out
}
